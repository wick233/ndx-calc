"""Generate the QQQ monthly backtest asset from Yahoo Finance daily bars."""

import argparse
import csv
import json
import math
import os
import sys
from datetime import date, datetime, timezone
from pathlib import Path
from urllib.request import Request, urlopen
from urllib.parse import urlsplit

LISTED = date(1999, 3, 10)
HOSTS = ("query1.finance.yahoo.com", "query2.finance.yahoo.com")


def monthly(payload, today):
    result, = payload["chart"]["result"]
    if result["meta"]["symbol"] != "QQQ":
        raise ValueError("unexpected ticker")
    timestamps = result["timestamp"]
    closes = result["indicators"]["quote"][0]["close"]
    adjusted = result["indicators"]["adjclose"][0]["adjclose"]
    current = today.year * 12 + today.month - 1
    if not timestamps or datetime.fromtimestamp(timestamps[0], timezone.utc).date() != LISTED:
        raise ValueError("history does not start at QQQ inception")
    months = {}
    for stamp, close, adj in sorted(zip(timestamps, closes, adjusted, strict=True)):
        day = datetime.fromtimestamp(stamp, timezone.utc).date()
        month = day.year * 12 + day.month - 1
        if month < current:
            months[month] = (close, adj)
    return validate_months(months, today)


def validate_months(months, today):
    current = today.year * 12 + today.month - 1
    expected = range(LISTED.year * 12 + LISTED.month - 1, current)
    if not expected or sorted(months) != list(expected):
        raise ValueError("missing completed months")
    if any(not isinstance(v, (float, int)) or not math.isfinite(v) or v <= 0
           for pair in months.values() for v in pair):
        raise ValueError("invalid month-end prices")
    def label(month):
        return f"{month // 12:04d}-{month % 12 + 1:02d}"
    return dict(start=label(expected[0]), end=label(expected[-1]), months=len(expected),
                closes=[round(months[m][0], 6) for m in expected],
                adjusted=[round(months[m][1], 6) for m in expected])


def published_monthly(lines, today):
    reader = csv.DictReader(lines)
    if reader.fieldnames != ["symbol", "month", "close", "adjusted"]:
        raise ValueError("expected CSV columns: symbol,month,close,adjusted")
    current = today.year * 12 + today.month - 1
    months = {}
    for row in reader:
        if row["symbol"] != "QQQ":
            raise ValueError("unexpected ticker")
        day = date.fromisoformat(row["month"] + "-01")
        month = day.year * 12 + day.month - 1
        if month >= current or month in months:
            raise ValueError("incomplete or duplicate month")
        months[month] = (float(row["close"]), float(row["adjusted"]))
    return validate_months(months, today)


def write_asset(output, data, today, source):
    if output.is_file():
        try:
            old = json.loads(output.read_text(encoding="utf-8").split("window.QQQ_DATA = ", 1)[1].strip().removesuffix(";"))
            if old.get("source") == source and all(old.get(k) == v for k, v in data.items()):
                print(f"QQQ: unchanged ({data['end']})")
                return
        except (ValueError, IndexError, AttributeError):
            pass
    data.update(updated=today.isoformat(), source=source)
    tmp = output.with_suffix(".js.tmp")
    tmp.write_text("/* QQQ month-end prices, generated by update_qqq.py. */\nwindow.QQQ_DATA = "
                   + json.dumps(data, separators=(",", ":"), allow_nan=False) + ";\n", encoding="utf-8")
    tmp.replace(output)
    print(f"QQQ: {data['start']} to {data['end']} ({data['months']} months), {source}")


def main(output, publish=False):
    now = datetime.now(timezone.utc)
    if publish:
        url = os.environ.get("QQQ_PUBLISH_CSV_URL", "")
        try:
            if urlsplit(url).scheme != "https" or not urlsplit(url).hostname:
                raise ValueError("HTTPS CSV URL required")
            with urlopen(url, timeout=25) as response:
                if urlsplit(response.geturl()).scheme != "https":
                    raise ValueError("HTTPS response required")
                raw = response.read(1_000_001)
                if len(raw) > 1_000_000:
                    raise ValueError("CSV too large")
            data = published_monthly(raw.decode("utf-8-sig").splitlines(), now.date())
        except (OSError, ValueError, TypeError, csv.Error) as exc:
            print(f"QQQ: publish source unavailable or invalid ({type(exc).__name__})", file=sys.stderr)
            return 1
        write_asset(output, data, now.date(), "configured-csv")
        return 0
    for host in HOSTS:
        url = (f"https://{host}/v8/finance/chart/QQQ"
               f"?period1=920937600&period2={int(now.timestamp())}&interval=1d")
        try:
            with urlopen(Request(url, headers={"User-Agent": "Mozilla/5.0"}), timeout=25) as response:
                data = monthly(json.load(response), now.date())
        except (OSError, ValueError, KeyError, TypeError, IndexError) as exc:
            print(f"QQQ: {host}: {exc}", file=sys.stderr)
            continue
        write_asset(output, data, now.date(), host)
        return 0
    return 1


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, nargs="?", default=Path(__file__).with_name("qqq-data.js"))
    parser.add_argument("--publish", action="store_true", help="use the configured publication CSV only")
    args = parser.parse_args()
    sys.exit(main(args.output, args.publish))
